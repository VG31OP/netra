use netra_capture::CaptureManager;

#[test]
fn generate_rich_sample_pcap() {
    let mut packets = Vec::new();

    // 1. ARP Request
    let arp_pkt = vec![
        0xff, 0xff, 0xff, 0xff, 0xff, 0xff, // Dst MAC: Broadcast
        0x00, 0x11, 0x22, 0x33, 0x44, 0x55, // Src MAC
        0x08, 0x06,                         // EtherType: ARP
        0x00, 0x01, 0x08, 0x00, 0x06, 0x04, 0x00, 0x01, // ARP Header
        0x00, 0x11, 0x22, 0x33, 0x44, 0x55, 192, 168, 1, 50, // Sender MAC & IP
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 192, 168, 1, 1,  // Target MAC & IP
    ];
    packets.push(arp_pkt);

    // 2. DNS Query for google.com
    let dns_pkt = vec![
        0x00, 0x50, 0x56, 0xc0, 0x00, 0x08, // Dst MAC
        0x00, 0x11, 0x22, 0x33, 0x44, 0x55, // Src MAC
        0x08, 0x00,                         // EtherType: IPv4
        0x45, 0x00, 0x00, 0x37, 0x1a, 0x2b, 0x00, 0x00, 0x40, 0x11, 0x00, 0x00, // IPv4 header
        192, 168, 1, 50, 8, 8, 8, 8,        // 192.168.1.50 -> 8.8.8.8
        0xc0, 0x01, 0x00, 0x35, 0x00, 0x23, 0x00, 0x00, // UDP: 49153 -> 53
        0x12, 0x34, 0x01, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, // DNS header
        0x06, b'g', b'o', b'o', b'g', b'l', b'e', 0x03, b'c', b'o', b'm', 0x00, // google.com
        0x00, 0x01, 0x00, 0x01,             // Type A, Class IN
    ];
    packets.push(dns_pkt);

    // 3. TCP SYN (Client 192.168.1.100:54321 -> Server 192.168.1.1:80)
    let tcp_syn = vec![
        0x00, 0x50, 0x56, 0xc0, 0x00, 0x01, // Dst MAC
        0x00, 0x11, 0x22, 0x33, 0x44, 0x55, // Src MAC
        0x08, 0x00,                         // EtherType: IPv4
        0x45, 0x00, 0x00, 0x34, 0x2a, 0x11, 0x40, 0x00, 0x40, 0x06, 0x00, 0x00, // IPv4 header
        192, 168, 1, 100, 192, 168, 1, 1,   // 192.168.1.100 -> 192.168.1.1
        0xd4, 0x31, 0x00, 0x50,             // Src port 54321, Dst port 80
        0x00, 0x00, 0x10, 0x00,             // Seq: 4096
        0x00, 0x00, 0x00, 0x00,             // Ack: 0
        0x50, 0x02, 0xfa, 0xf0, 0x00, 0x00, 0x00, 0x00, // Flags: SYN, Win: 64240
    ];
    packets.push(tcp_syn);

    // 4. TCP HTTP GET Request (Client -> Server)
    let http_payload = b"GET /index.html HTTP/1.1\r\nHost: 192.168.1.1\r\nUser-Agent: Netra/0.1\r\nAccept: */*\r\n\r\n";
    let mut tcp_http_req = vec![
        0x00, 0x50, 0x56, 0xc0, 0x00, 0x01,
        0x00, 0x11, 0x22, 0x33, 0x44, 0x55,
        0x08, 0x00,
        0x45, 0x00, 0x00, (40 + http_payload.len()) as u8, 0x2a, 0x12, 0x40, 0x00, 0x40, 0x06, 0x00, 0x00,
        192, 168, 1, 100, 192, 168, 1, 1,
        0xd4, 0x31, 0x00, 0x50,
        0x00, 0x00, 0x10, 0x01,             // Seq: 4097
        0x00, 0x00, 0x20, 0x01,             // Ack: 8193
        0x50, 0x18, 0xfa, 0xf0, 0x00, 0x00, 0x00, 0x00, // Flags: ACK, PSH
    ];
    tcp_http_req.extend_from_slice(http_payload);
    packets.push(tcp_http_req);

    // 5. TCP HTTP Response (Server -> Client)
    let resp_payload = b"HTTP/1.1 200 OK\r\nServer: Apache/2.4.52 (Ubuntu)\r\nContent-Type: text/html\r\nContent-Length: 35\r\n\r\n<h1>NETRA Engine Online</h1>\n";
    let mut tcp_http_resp = vec![
        0x00, 0x11, 0x22, 0x33, 0x44, 0x55,
        0x00, 0x50, 0x56, 0xc0, 0x00, 0x01,
        0x08, 0x00,
        0x45, 0x00, 0x00, (40 + resp_payload.len()) as u8, 0x3b, 0x21, 0x40, 0x00, 0x40, 0x06, 0x00, 0x00,
        192, 168, 1, 1, 192, 168, 1, 100,
        0x00, 0x50, 0xd4, 0x31,
        0x00, 0x00, 0x20, 0x01,             // Seq: 8193
        0x00, 0x00, 0x10, (1 + http_payload.len()) as u8, // Ack
        0x50, 0x18, 0xfa, 0xf0, 0x00, 0x00, 0x00, 0x00, // Flags: ACK, PSH
    ];
    tcp_http_resp.extend_from_slice(resp_payload);
    packets.push(tcp_http_resp);

    // 6. TLS ClientHello with SNI api.github.com
    let tls_sni_pkt = vec![
        0x00, 0x50, 0x56, 0xc0, 0x00, 0x01,
        0x00, 0x11, 0x22, 0x33, 0x44, 0x55,
        0x08, 0x00,
        0x45, 0x00, 0x00, 0x55, 0x4c, 0x13, 0x40, 0x00, 0x40, 0x06, 0x00, 0x00,
        192, 168, 1, 100, 140, 82, 121, 4, // 140.82.121.4 (GitHub)
        0xd4, 0x32, 0x01, 0xbb,             // 54322 -> 443
        0x00, 0x00, 0x30, 0x01,
        0x00, 0x00, 0x00, 0x00,
        0x50, 0x18, 0xfa, 0xf0, 0x00, 0x00, 0x00, 0x00,
        // TLS Record + ClientHello
        0x16, 0x03, 0x01, 0x00, 0x28, // Record: Handshake, TLS 1.0, len 40
        0x01, 0x00, 0x00, 0x24,       // Handshake: ClientHello
        0x03, 0x03,                   // TLS 1.2
        0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07,
        0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e, 0x0f,
        0x00, 0x00, 0x02, 0x00, 0x2f, // Cipher suite
        0x01, 0x00,                   // Compression: null
        0x00, 0x13,                   // Extensions length 19
        0x00, 0x00, 0x00, 0x0f, 0x00, 0x0d, 0x00, 0x00, 0x0e,
        b'a', b'p', b'i', b'.', b'g', b'i', b't', b'h', b'u', b'b', b'.', b'c', b'o', b'm',
    ];
    packets.push(tls_sni_pkt);

    // Write to sample_capture.pcap
    CaptureManager::export_to_pcap(&packets, "sample_capture.pcap").expect("Failed to export rich PCAP");
    println!("Successfully generated rich sample_capture.pcap with {} packets", packets.len());
}
